;RESTARTING INIT
INITAT:
	inc CHRGET+7	;INCREMENT THE WHOLE TXTPTR.
	bne CHZGOT
	inc CHRGET+8
CHZGOT:
	lda $ea60	;A LOAD WITH AN EXT ADDR.
	cmp #58	;IS IT A ":"?
	bcs CHZRTS	;IT IS .GE. ":"
	cmp #32	;SKIP SPACES.
	beq INITAT
	sec
	sbc #48	;ALL CHARS .GT. "9" HAVE RET'D SO
	sec
	sbc #$100-48	;SEE IF NUMERIC.
;TURN CARRY ON IF NUMERIC.
;ALSO, SETZ IF NULL.
CHZRTS:
	rts	;RETURN TO CALLER.

	.byte $80	;LOADED OR FROM ROM.
	.byte $4f	;THE INITIAL RANDOM NUMBER.
	.byte $c7
	.byte $52
	.byte $58


TYPAUT:
;LDWDI AUTTXT

	lda #[[AUTTXT]&$ff]
	ldy #[[AUTTXT]/$100]
	jsr STROUT
INIT:

	ldx #$ff	;MAKE IT LOOK DIRECT IN CASE OF
	stx CURLIN+1
;ERROR MESSAGE.

	ldx #STKEND-$100
	txs

;LDWDI INIT  ;ALLOW RESTART.

	lda #[[INIT]&$ff]
	ldy #[[INIT]/$100]
;STWD START+1

	sta START+1
	sty 0+[START+1]+1
;STWD RDYJSR+1  ;RTS HERE ON ERRORS.

	sta RDYJSR+1
	sty 0+[RDYJSR+1]+1
;LDWDI AYINT

	lda #[[AYINT]&$ff]
	ldy #[[AYINT]/$100]
;STWD ADRAYI

	sta ADRAYI
	sty 0+[ADRAYI]+1
;LDWDI GIVAYF

	lda #[[GIVAYF]&$ff]
	ldy #[[GIVAYF]/$100]
;STWD ADRGAY

	sta ADRGAY
	sty 0+[ADRGAY]+1
	lda #$4c	;JMP INSTRUCTION.
;MAKE AN INST.

	sta START
	sta RDYJSR
	sta JMPER

	sta USRPOK
;LDWDI FCERR

	lda #[[FCERR]&$ff]
	ldy #[[FCERR]/$100]
;STWD USRPOK+1

	sta USRPOK+1
	sty 0+[USRPOK+1]+1
	lda #LINLEN	;THESE MUST BE NON-ZERO SO CHEAD WILL
	sta LINWID	;WORK AFTER MOVING A NEW LINE IN BUF
;INTO THE PROGRAM
	lda #NCMPOS
	sta NCMWID
	ldx #RNDX+4-CHRGET
MOVCHG:
	lda INITAT-1,x
	sta CHRGET-1,x	;MOVE TO RAM.
	dex
	bne MOVCHG
	lda #STRSIZ
	sta FOUR6
	txa	;SET CONST IN RAM.
	sta BITS
	sta LASTPT+1
	pha	;PUT ZERO AT THE END OF THE STACK
;SO FNDFOR WILL STOP

	sta CNTWFL
;BE TALKATIVE.

	inx	;MAKE [X]=1
	stx BUF-3	;SET PRE-BUF BYTES NON-ZERO FOR CHEAD
	stx BUF-4

	jsr CRDO
;TYPE A CR.
	ldx #TEMPST
	stx TEMPPT	;SET UP STRING TEMPORARIES.


;LDWDI MEMORY

;--- MERIDIAN: Keine Fragen nach Speichergroesse und Zeilenbreite: der Speicher endet vor dem BASIC-Code
	jmp M_SPEICHER	;MERIDIAN: Speicher bis ROMLOC, keine Fragen
	jsr QINLIN	;GET A LINE OF INPUT.
;STXY TXTPTR  ;READ THIS !

	stx TXTPTR
	sty 0+[TXTPTR]+1
	jsr CHRGET	;GET THE FIRST CHARACTER.

	cmp #65	;IS IT AN "A"?
	beq TYPAUT
;YES TYPE AUTHOR'S NAME.
	tay	;NULL INPUT?
	bne USEDE9
;NO.

;YES GET PNTR TO LAST WORD.

;LDWDI RAMLOC

	lda #[[RAMLOC]&$ff]
	ldy #[[RAMLOC]/$100]

;STWD TXTTAB

	sta TXTTAB
	sty 0+[TXTTAB]+1
;SET UP START OF PROGRAM LOCATION
;STWD LINNUM

	sta LINNUM
	sty 0+[LINNUM]+1

	ldy #0
LOOPMM:
	inc LINNUM
	bne LOOPM1
	inc LINNUM+1
LOOPM1:
	lda #$55	;PUT RANDOM INFO INTO MEM.
	sta (LINNUM),y
	cmp (LINNUM),y	;WAS IT SAVED?
	bne USEDEC	;NO. THAT IS END OF MEMORY.
	asl a	;LOOKS LIKE IT. TRY ANOTHER.
	sta (LINNUM),y
	cmp (LINNUM),y	;WAS IT SAVED?

	bne USEDEC
;NO. THIS IS THE END.

	beq LOOPMM

USEDE9:
	jsr CHRGOT	;GET CURRENT CHARACTER.
	jsr LINGET	;GET DECIMAL ARGUMENT.
	tay	;MAKE SURE A TERMINATOR EXISTS.
	beq USEDEC	;IT DOES.
	jmp SNERR
;IT DOESN'T.
USEDEC:
;LDWD LINNUM  ;GET SIZE OF MEMORY INPUT.

	lda LINNUM
	ldy 0+[LINNUM]+1
USEDEF:
;HIGHEST ADDRESS.
;A STRANGE NUMBER.
;STWD MEMSIZ  ;THIS IS THE SIZE OF MEMORY.

	sta MEMSIZ
	sty 0+[MEMSIZ]+1
;STWD FRETOP  ;TOP OF STRINGS TOO.

	sta FRETOP
	sty 0+[FRETOP]+1
TTYW:


;LDWDI TTYWID

	lda #[[TTYWID]&$ff]
	ldy #[[TTYWID]/$100]
	jsr STROUT
	jsr QINLIN	;GET LINE OF INPUT.
;STXY TXTPTR  ;READ THIS !

	stx TXTPTR
	sty 0+[TXTPTR]+1
	jsr CHRGET	;GET FIRST CHARACTER.
	tay	;TEST ACCA BUT DON'T AFFECT CARRY.
	beq ASKAGN
	jsr LINGET	;GET ARGUMENT.
	lda LINNUM+1
	bne TTYW	;WIDTH MUST BE .LT. 256.
	lda LINNUM
	cmp #$10	;WIDTH MUST BE GREATER THAN 16.
	bcc TTYW
	sta LINWID	;THAT IS THE LINE WIDTH.
MORCPS:
	sbc #CLMWID	;COMPUTE POSITION BEYOND WHICH
	bcs MORCPS	;THERE ARE NO MORE FIELDS.
	eor #$ff
	sbc #CLMWID-2
	clc
	adc LINWID
	sta NCMWID
ASKAGN:
;GET RID OF ALL UP TO "INITAT".

;LDXYI RAMLOC

	ldx #[[RAMLOC]&$ff]
	ldy #[[RAMLOC]/$100]
;STXY TXTTAB

	stx TXTTAB
	sty 0+[TXTTAB]+1
	ldy #0
	tya
	sta (TXTTAB),y	;SET UP TEXT TABLE.
	inc TXTTAB

	bne QROOM
	inc TXTTAB+1
QROOM:
;LDWD TXTTAB  ;PREPARE TO USE "REASON".

	lda TXTTAB
	ldy 0+[TXTTAB]+1
	jsr REASON

	jsr CRDO
	lda MEMSIZ	;COMPUTE [MEMSIZ]-[VARTAB].
	sec
	sbc TXTTAB
	tax
	lda MEMSIZ+1
	sbc TXTTAB+1
	jsr LINPRT	;TYPE THIS VALUE.
;LDWDI WORDS  ;MORE BULLSHIT.

	lda #[[WORDS]&$ff]
	ldy #[[WORDS]/$100]
	jsr STROUT
	jsr SCRTCH	;SET UP EVERYTHING ELSE.

;LDWDI STROUT

	lda #[[STROUT]&$ff]
	ldy #[[STROUT]/$100]
;STWD RDYJSR+1

	sta RDYJSR+1
	sty 0+[RDYJSR+1]+1
;LDWDI READY

	lda #[[READY]&$ff]
	ldy #[[READY]/$100]
;STWD START+1

	sta START+1
	sty 0+[START+1]+1
	jmp (START+1)



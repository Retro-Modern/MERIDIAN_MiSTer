DATLOP:
	jsr DATAN	;SKIP SOME TEXT.
	iny
	tax	;END OF LINE?
	bne NOWLIN	;SHO AIN'T.
	ldx #ERROD	;YES = "NO DATA" ERROR.
	iny
	lda (TXTPTR),y
	beq ERRGO5
	iny

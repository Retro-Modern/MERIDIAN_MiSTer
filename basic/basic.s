;RELINK THE PROGRAM

SAVE:
	sec	;CALCLUATE PROGRAM SIZE IN POKER
	lda VARTAB
	sbc TXTTAB
	sta POKER
	lda VARTAB+1
	sbc TXTTAB+1
	sta POKER+1
;--- MERIDIAN: SAVE in den Zusatzspeicher statt auf Kassette
	jmp M_SAVE	;MERIDIAN: Programm nach Bank $10

;--- MERIDIAN: LOAD aus dem Zusatzspeicher
LOAD:
	jsr M_LOAD	;MERIDIAN: Laenge nach POKER, Programm zurueck
	clc
	lda TXTTAB	;CALCULATE VARTAB FROM SIZE AND
	adc POKER	;TXTTAB
	sta VARTAB
	lda TXTTAB+1
	adc POKER+1
	sta VARTAB+1
;--- MERIDIAN: LOAD liest das Programm schon in M_LOAD
	;MERIDIAN: Programm steht schon im Speicher
;LDWDI TPDONE

	lda #[[TPDONE]&$ff]
	ldy #[[TPDONE]/$100]
;--- MERIDIAN: Nach LOAD: READY. wie beim C64
	jsr STROUT
	jsr RUNC
	jsr LNKPRG

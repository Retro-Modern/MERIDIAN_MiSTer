	.byte $4c, $4f, $41, $44, $45, $44
	.byte 0

VARTIO:
;LDWDI POKER

	lda #[[POKER]&$ff]
	ldy #[[POKER]/$100]
;STWD ^O74

	sta $3c
	sty 0+[$3c]+1
	lda #POKER+2
;STWD ^O76

	sta $3e
	sty 0+[$3e]+1
	rts
PROGIO:
;LDWD TXTTAB

	lda TXTTAB
	ldy 0+[TXTTAB]+1
;STWD ^O74

	sta $3c
	sty 0+[$3c]+1
;LDWD VARTAB

	lda VARTAB
	ldy 0+[VARTAB]+1
;STWD ^O76

	sta $3e
	sty 0+[$3e]+1
	rts

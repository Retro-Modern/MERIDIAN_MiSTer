	rts	;RETURN TO CALLER.

NOTFNS:
	pla	;CHECK WHO'S CALLING.
	pha	;RESTORE IT.
	cmp #ISVRET-1-[ISVRET-1]/$100*$100	;IS EVAL CALLING?
	bne NOTEVL	;NO, CARRY ON.

	tsx
	lda $102,x
	cmp #[[ISVRET-1]/$100]
	bne NOTEVL
LDZR:
;LDWDI ZERO  ;SET UP PNTR TO SIMULATED ZERO.

	lda #[[ZERO]&$ff]
	ldy #[[ZERO]/$100]
	rts	;FOR STRINGS OR NUMERIC.
;AND FOR INTEGERS TOO.
NOTEVL:
QSTAVR:
VAROK:
;LDWD ARYTAB

	lda ARYTAB
	ldy 0+[ARYTAB]+1
;STWD LOWTR  ;LOWEST THING TO MOVE.

	sta LOWTR
	sty 0+[LOWTR]+1
;LDWD STREND  ;GET HIGHEST ADDR TO MOVE.

	lda STREND
	ldy 0+[STREND]+1
;STWD HIGHTR


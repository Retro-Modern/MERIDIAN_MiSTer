;STWD FORPNT  ;INTO "FORPNT".

	sta FORPNT
	sty 0+[FORPNT]+1
	jsr FNDFOR	;FIND THE MATCHING ENTRY IF ANY.
	beq HAVFOR
	ldx #ERRNF	;"NEXT WITHOUT FOR".
ERRGO5:
	beq ERRGO4

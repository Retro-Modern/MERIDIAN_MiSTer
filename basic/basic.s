	sty 0+[HIGHDS]+1
	jsr BLTU	;MOVE IT ALL.
;NOTE [Y,A] HAS [HIGHDS] FOR REASON.
;LDWD HIGHDS  ;AND SET UP

	lda HIGHDS
	ldy 0+[HIGHDS]+1
	iny
;STWD ARYTAB  ;NEW START OF ARRAY TABLE.

	sta ARYTAB
	sty 0+[ARYTAB]+1
	ldy #0	;GET ADDR OF VARIABLE ENTRY.
	lda VARNAM
	sta (LOWTR),y
	iny
	lda VARNAM+1
	sta (LOWTR),y	;STORE NAME OF VARIABLE.
	lda #0
	iny
	sta (LOWTR),y
	iny
	sta (LOWTR),y
	iny
	sta (LOWTR),y
	iny

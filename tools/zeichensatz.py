# Achtelbalken (Etappe 6, fuer Pegelanzeigen): $A0-$A6 senkrecht 1/8 bis
# 7/8 von unten (8/8 ist $8B); $B1-$B8 waagrecht 1/8 bis 8/8 von links,
# nur sechs Pixel hoch - so sitzt ein Balken mit Luft in seiner Zeile
for n in range(1, 8):
    glyph(0x9F + n, *([_] * (8 - n) + ["########"] * n))
for n in range(1, 9):
    glyph(0xB0 + n, _, *(["#" * n + "." * (8 - n)] * 6), _)


def daten():
    out = bytearray(256 * 8)
    for code, zeilen in G.items():
        for r, z in enumerate(zeilen):
            out[code * 8 + r] = int(z.replace("#", "1").replace(".", "0"), 2)
    return out


def vorschau(daten, pfad):
    try:
        from PIL import Image
    except ImportError:
        return
    s = 3
    img = Image.new("RGB", (16 * 9 * s, 16 * 9 * s), (18, 28, 70))
    for code in range(256):
        cx, cy = (code % 16) * 9 * s, (code // 16) * 9 * s
        for r in range(8):
            byte = daten[code * 8 + r]
            for x in range(8):
                if byte & (0x80 >> x):
                    for dy in range(s):
                        for dx in range(s):
                            img.putpixel((cx + x * s + dx, cy + r * s + dy), (150, 190, 255))
    img.save(pfad)


def main():
    d = daten()
    os.makedirs(os.path.join(BASIS, "rom"), exist_ok=True)
    with open(os.path.join(BASIS, "rom", "zeichensatz.bin"), "wb") as f:
        f.write(d)
    os.makedirs(os.path.join(BASIS, "doku", "bilder"), exist_ok=True)
    vorschau(d, os.path.join(BASIS, "doku", "bilder", "zeichensatz.png"))
    print(f"{len(G)} Zeichen entworfen, rom/zeichensatz.bin ({len(d)} Bytes)")


if __name__ == "__main__":
    main()

def glyph(zeichen, *zeilen):
    zeilen = list(zeilen) + [_] * (8 - len(zeilen))
    assert len(zeilen) == 8 and all(len(z) == 8 for z in zeilen), zeichen
    code = zeichen if isinstance(zeichen, int) else ord(zeichen)
    assert code not in G, zeichen
    G[code] = zeilen


